sans indemnité.
</p>

<h2>5. Obligations du conducteur</h2>
<ul>
    <li>Détenir un permis de conduire valide</li>
    <li>Être assuré pour le transport de passagers</li>
    <li>Proposer un véhicule en état de circuler</li>
    <li>Ne demander qu’une participation aux frais</li>
</ul>

<h2>6. Obligations du passager</h2>
